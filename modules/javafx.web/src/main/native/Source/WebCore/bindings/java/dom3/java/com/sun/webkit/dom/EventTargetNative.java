package com.sun.webkit.dom;

import com.sun.webkit.WebKitNative;
import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.MemorySegment;
import java.lang.invoke.MethodHandle;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;

/**
 * FFM facade for the {@code wkj_dom_EventTarget_*} functions of the {@code jfxwebkit} C ABI, used by
 * {@link EventTargetImpl}. One facade per DOM type keeps symbol resolution lazy: the handles below are
 * bound the first time this type is touched, not the first time any DOM object is.
 * <p>
 * Generated by {@code buildtools/ffm-web/dom-java-to-ffm.pl} from
 * {@code buildtools/ffm-web/dom-abi.tsv}. Do not edit; regenerate.
 * <p>
 * These downcalls deliberately do not use {@code Linker.Option.critical(true)}, and no downcall in
 * this layer may. A DOM read or mutation can synchronously run script and fire event listeners,
 * which upcall into Java, and a critical downcall forbids upcalls. The gain would be one avoided
 * copy of a string; the cost would be an intermittent crash.
 *
 * @see com.sun.webkit.WebKitNative
 */
final class EventTargetNative {

    private static final MethodHandle DISPOSE = WebKitNative.downcall("wkj_dom_EventTarget_dispose",
            FunctionDescriptor.ofVoid(JAVA_LONG));
    private static final MethodHandle ADD_EVENT_LISTENER = WebKitNative.downcall("wkj_dom_EventTarget_addEventListener",
            FunctionDescriptor.ofVoid(JAVA_LONG, ADDRESS, JAVA_INT, JAVA_LONG, JAVA_INT));
    private static final MethodHandle REMOVE_EVENT_LISTENER = WebKitNative.downcall(
            "wkj_dom_EventTarget_removeEventListener",
            FunctionDescriptor.ofVoid(JAVA_LONG, ADDRESS, JAVA_INT, JAVA_LONG, JAVA_INT));
    private static final MethodHandle DISPATCH_EVENT = WebKitNative.downcall("wkj_dom_EventTarget_dispatchEvent",
            FunctionDescriptor.of(JAVA_INT, JAVA_LONG, JAVA_LONG));

    private EventTargetNative() {
    }

    static void dispose(long peer) {
        try {
            DISPOSE.invokeExact(peer);
        } catch (Throwable t) {
            throw new AssertionError(t);
        }
    }

    static void addEventListener(long peer, String type, long listener, boolean useCapture) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment typeSegment = WebKitNative.allocString(arena, type);
            try {
                ADD_EVENT_LISTENER.invokeExact(peer, typeSegment, WebKitNative.stringLength(type), listener,
                        useCapture ? 1 : 0);
            } catch (Throwable t) {
                throw new AssertionError(t);
            }
        }
    }

    static void removeEventListener(long peer, String type, long listener, boolean useCapture) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment typeSegment = WebKitNative.allocString(arena, type);
            try {
                REMOVE_EVENT_LISTENER.invokeExact(peer, typeSegment, WebKitNative.stringLength(type), listener,
                        useCapture ? 1 : 0);
            } catch (Throwable t) {
                throw new AssertionError(t);
            }
        }
    }

    static boolean dispatchEvent(long peer, long event) {
        int result;
        try {
            result = (int) DISPATCH_EVENT.invokeExact(peer, event);
        } catch (Throwable t) {
            throw new AssertionError(t);
        }
        WebKitNative.checkException();
        return result != 0;
    }
}
